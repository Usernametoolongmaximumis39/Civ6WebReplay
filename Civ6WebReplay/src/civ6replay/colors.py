PLAYER_COLORS_JSON = Path(__file__).resolve().parents[2] / "data/shared/player-colors.json"


@lru_cache(maxsize=1)
def _shared_colors():
    if not PLAYER_COLORS_JSON.exists():
        return {}
    doc = json.loads(PLAYER_COLORS_JSON.read_text(encoding="utf-8"))
    return {profile: {crc32_type(type_str): [v for rgba in doc["palettes"][key] for v in rgba]
                      for type_str, key in rows.items()}
            for profile, rows in doc["profiles"].items()}


def player_color_profile(mods=()) -> str:
    """CCB takes precedence when its save also lists a BBG dependency."""
    titles = "\n".join(str(title) for title in mods)
    if re.search(r"\bccb\b|和而不同", titles, re.I):
        return "ccb"
    if re.search(r"\bbbg\b|better\s+balanced", titles, re.I):
        return "bbg"
    return "shared"


def leader_color_pair(leader: int, color_index: int = 0, *, profile: str = "shared"):
    """Resolve a save's jersey index to its two normalized RGBA colors.

    Bundled mod rows override the original table only in their own profile.
    Unknown indices use the leader's default jersey, never an empty slice.
    """
    tables = _shared_colors()
    table = tables.get(profile, {}).get(leader & 0xFFFFFFFF)
    if table is None:
        table = LEADER_COLORS.get(leader & 0xFFFFFFFF)
    if table is None:
        table = tables.get("shared", {}).get(leader & 0xFFFFFFFF)
    if not table:
        return None
    base = color_index * 8
    if base < 0 or base + 8 > len(table):
        base = 0
    # Preserve the existing vanilla normalization used by the map and HUD.
    return (tuple(c / 256.0 for c in table[base:base + 4]),
            tuple(c / 256.0 for c in table[base + 4:base + 8]))


